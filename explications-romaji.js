 const run=/[一-鿿ぁ-ゖァ-ヺー々]+/g;
 function explain(value){
  const text=String(value??'');
  return text.replace(run,(jp,offset)=>{
   const reading=readings[jp];if(!reading)return jp;
   const before=text.slice(0,offset),after=text.slice(offset+jp.length);
   // Ne pas annoter à nouveau une lecture kana dans une parenthèse kana/romaji.
   const left=Math.max(before.lastIndexOf('('),before.lastIndexOf('（'));
   const right=Math.max(before.lastIndexOf(')'),before.lastIndexOf('）'));
   if(left>right&&/[A-Za-zāīūēō]/.test(text.slice(left).split(/[)）]/)[0]))return jp;
   // Une parenthèse de lecture préparée existe déjà juste après ce fragment.
   const parenthesis=after.match(/^\s*[（(]([^）)]*)[）)]/);
   if(parenthesis&&/[A-Za-zāīūēō]/.test(parenthesis[1]))return jp;
   const display=root.Romaji?root.Romaji.display(reading):reading;
   return jp+' ('+display+')';
  });
 }
